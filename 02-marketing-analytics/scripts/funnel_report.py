"""Marketing funnel & ROI report.

Reads campaign-level data (CSV) and produces an executive Markdown report:
funnel conversion, cost per stage, pipeline per $, CAC, ROI and velocity by channel.

Usage:
    python scripts/funnel_report.py data/sample_campaigns.csv [--out report.md]

Standard library only. The sample data is synthetic.
"""
import argparse
import csv
from collections import defaultdict

NUMERIC = ["spend_usd", "leads", "mqls", "sqls", "opportunities",
           "pipeline_usd", "won_deals", "revenue_usd"]


def load(path):
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        for k in NUMERIC + ["avg_days_to_close"]:
            r[k] = float(r[k])
    return rows


def aggregate(rows, key):
    out = defaultdict(lambda: defaultdict(float))
    for r in rows:
        g = out[r[key]]
        for k in NUMERIC:
            g[k] += r[k]
        # weight close-time by won deals so the channel average is meaningful
        g["_days_weighted"] += r["avg_days_to_close"] * r["won_deals"]
    for g in out.values():
        g["avg_days_to_close"] = g["_days_weighted"] / g["won_deals"] if g["won_deals"] else 0
    return out


def div(a, b):
    return a / b if b else 0.0


def pct(a, b):
    return f"{div(a, b) * 100:.0f}%"


def money(x):
    return f"${x:,.0f}"


def velocity(g):
    """Pipeline velocity ($/day) = opportunities x win rate x avg deal size / cycle days."""
    win_rate = div(g["won_deals"], g["opportunities"])
    deal = div(g["revenue_usd"], g["won_deals"])
    return div(g["opportunities"] * win_rate * deal, g["avg_days_to_close"])


def build_report(rows):
    total = defaultdict(float)
    for r in rows:
        for k in NUMERIC:
            total[k] += r[k]
    by_channel = aggregate(rows, "channel")
    by_quarter = aggregate(rows, "quarter")

    lines = ["# Marketing Performance Report", "",
             "_Generated by `funnel_report.py`._", "",
             "## Executive Summary", "",
             "| Metric | Value |", "|---|---|",
             f"| Marketing spend | {money(total['spend_usd'])} |",
             f"| Pipeline created | {money(total['pipeline_usd'])} |",
             f"| Closed revenue | {money(total['revenue_usd'])} |",
             f"| Pipeline per $1 spent | {div(total['pipeline_usd'], total['spend_usd']):.1f}x |",
             f"| Marketing ROI (revenue / spend) | {div(total['revenue_usd'], total['spend_usd']):.1f}x |",
             f"| Blended CAC | {money(div(total['spend_usd'], total['won_deals']))} |",
             f"| Lead → Won conversion | {div(total['won_deals'], total['leads']) * 100:.2f}% |",
             "", "## Funnel Conversion", "",
             "| Stage | Volume | Conversion from previous |", "|---|---|---|"]
    stages = [("Leads", "leads"), ("MQLs", "mqls"), ("SQLs", "sqls"),
              ("Opportunities", "opportunities"), ("Won deals", "won_deals")]
    prev = None
    for label, k in stages:
        conv = pct(total[k], total[prev]) if prev else "—"
        lines.append(f"| {label} | {total[k]:,.0f} | {conv} |")
        prev = k

    lines += ["", "## Channel Performance", "",
              "| Channel | Spend | Cost / SQL | Pipeline / $ | CAC | ROI | Win rate | Velocity ($/day) |",
              "|---|---|---|---|---|---|---|---|"]
    ranked = sorted(by_channel.items(),
                    key=lambda kv: div(kv[1]["pipeline_usd"], kv[1]["spend_usd"]), reverse=True)
    for ch, g in ranked:
        lines.append(
            f"| {ch} | {money(g['spend_usd'])} | {money(div(g['spend_usd'], g['sqls']))} | "
            f"{div(g['pipeline_usd'], g['spend_usd']):.1f}x | {money(div(g['spend_usd'], g['won_deals']))} | "
            f"{div(g['revenue_usd'], g['spend_usd']):.1f}x | {pct(g['won_deals'], g['opportunities'])} | "
            f"{money(velocity(g))} |")

    lines += ["", "## Quarter over Quarter", "",
              "| Quarter | Spend | SQLs | Pipeline | Revenue | Pipeline / $ |", "|---|---|---|---|---|---|"]
    for q, g in sorted(by_quarter.items()):
        lines.append(f"| {q} | {money(g['spend_usd'])} | {g['sqls']:,.0f} | {money(g['pipeline_usd'])} | "
                     f"{money(g['revenue_usd'])} | {div(g['pipeline_usd'], g['spend_usd']):.1f}x |")

    best, worst = ranked[0], ranked[-1]
    lines += ["", "## Recommendations", "",
              f"- **Scale:** {best[0]} returns the most pipeline per dollar "
              f"({div(best[1]['pipeline_usd'], best[1]['spend_usd']):.1f}x). Test a 10–20% budget increase and watch cost per SQL.",
              f"- **Fix or reduce:** {worst[0]} returns the least pipeline per dollar "
              f"({div(worst[1]['pipeline_usd'], worst[1]['spend_usd']):.1f}x). Tighten targeting or reallocate.",
              "- **Funnel:** Find the stage with the lowest conversion and agree a fix with Sales (lead definition, SLA or enablement).",
              ""]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("csv_path")
    p.add_argument("--out", help="write the report to this file instead of stdout")
    a = p.parse_args()
    report = build_report(load(a.csv_path))
    if a.out:
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(report)
        print(f"Report written to {a.out}")
    else:
        print(report)


if __name__ == "__main__":
    main()
